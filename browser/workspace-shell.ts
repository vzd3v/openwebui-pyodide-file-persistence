export function createShell(native: PyodideFS, root: string, readonlyInputs = true): Bash {
  return new Bash({
    fs: new WorkspaceFS(native, root, readonlyInputs),
    cwd: "/work",
    env: {
      HOME: "/work",
      TMPDIR: "/work/tmp",
      WORKSPACE: "/",
      INPUTS: "/inputs",
      SCRIPTS: "/scripts",
      OUTPUTS: "/outputs",
    },
    commands: [...COMMANDS],
    executionLimitProfile: "hardened",
    executionLimits: {
      maxExecutionTimeMs: 45000,
      maxOutputSize: 16 * 1024 * 1024,
      maxStringLength: 1024 * 1024 * 1024,
      maxArrayElements: 16 * 1024 * 1024,
      maxHeredocSize: 1024 * 1024 * 1024,
    },
  });
}

